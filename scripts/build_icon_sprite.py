"""Build static/tory/icons/lucide-sprite.svg from a lucide-static package (TORY-54).

Usage: python -I scripts/build_icon_sprite.py <path to lucide-static/package>

Only the icons listed in inventory_access/icons.py are included. Each icon is
parsed as XML and re-emitted with an allow-list of shape elements and geometry
attributes, so nothing but plain shapes reaches the sprite. Styling (stroke,
width, caps) comes from the .icon CSS class.
"""

import ast
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SVG = "{http://www.w3.org/2000/svg}"
SHAPES = {"path", "circle", "rect", "line", "polyline", "polygon", "ellipse"}
GEOMETRY = {"d", "cx", "cy", "r", "rx", "ry", "x", "y", "width", "height", "x1", "y1", "x2", "y2", "points"}


def icon_keys():
    tree = ast.parse((ROOT / "inventory_access" / "icons.py").read_text(encoding="utf-8"))
    for node in tree.body:
        if isinstance(node, ast.Assign) and getattr(node.targets[0], "id", "") == "ICONS":
            return [key for key, _label in ast.literal_eval(node.value)]
    raise SystemExit("ICONS not found")


def symbol(source, key):
    root = ET.parse(source / "icons" / f"{key}.svg").getroot()
    if root.tag != f"{SVG}svg" or root.get("viewBox") != "0 0 24 24":
        raise SystemExit(f"{key}: unexpected root element")
    shapes = []
    for child in root:
        name = child.tag.removeprefix(SVG)
        if name not in SHAPES or len(child):
            raise SystemExit(f"{key}: unexpected element {name}")
        attrs = " ".join(f'{attr}="{value}"' for attr, value in child.attrib.items() if attr in GEOMETRY)
        if any(ch in attrs for ch in "<>&"):
            raise SystemExit(f"{key}: unexpected characters")
        shapes.append(f"<{name} {attrs}/>")
    return f'<symbol id="{key}" viewBox="0 0 24 24">{"".join(shapes)}</symbol>'


def main(source):
    source = Path(source)
    version = __import__("json").loads((source / "package.json").read_text(encoding="utf-8"))["version"]
    out = ROOT / "static" / "tory" / "icons"
    out.mkdir(parents=True, exist_ok=True)
    symbols = "\n".join(symbol(source, key) for key in icon_keys())
    (out / "lucide-sprite.svg").write_text(
        f'<svg xmlns="http://www.w3.org/2000/svg">\n<!-- Lucide {version} (ISC licence, see LICENSE-lucide.txt). '
        f"Generated by scripts/build_icon_sprite.py; do not edit. -->\n{symbols}\n</svg>\n",
        encoding="utf-8", newline="\n",
    )
    (out / "LICENSE-lucide.txt").write_text((source / "LICENSE").read_text(encoding="utf-8"), encoding="utf-8",
                                            newline="\n")
    print(f"Wrote {len(icon_keys())} icons from Lucide {version}")


if __name__ == "__main__":
    main(sys.argv[1])
